#!/usr/bin/env python3
"""Generate research/INDEX.md from project overlays and markdown docs."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path


def _mtime(path: Path) -> str:
    return datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).strftime("%Y-%m-%d")


def _load_project(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return {}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--research", default="research")
    parser.add_argument("--output", default="research/INDEX.md")
    args = parser.parse_args()

    research = Path(args.research).resolve()
    if not research.is_dir():
        raise SystemExit(f"research directory is missing: {research}")

    rows = []
    for project_path in sorted(research.glob("*/project.json")):
        project = _load_project(project_path)
        claims = project.get("claims", []) or []
        blocked = sum(1 for c in claims if c.get("state") == "blocked")
        candidate = sum(1 for c in claims if c.get("state") in {"candidate", "inconclusive"})
        verified = sum(1 for c in claims if c.get("state") == "verified")
        package = (project.get("package") or {}).get("state", "unknown")
        rows.append({
            "dir": project_path.parent.name,
            "title": str(project.get("title") or "(untitled)"),
            "status": str(project.get("status") or "unknown"),
            "verified": verified,
            "candidate": candidate,
            "blocked": blocked,
            "package": package,
            "modified": _mtime(project_path),
        })

    docs = sorted(research.rglob("*.md"))
    doc_count = len([d for d in docs if d.name != "INDEX.md"])

    lines = [
        "# Research index",
        "",
        f"Generated: `{datetime.now(timezone.utc).isoformat().replace('+00:00', 'Z')}`",
        "",
        f"Overlays: {len(rows)} · Markdown documents: {doc_count}",
        "",
        "Machine-generated by `scripts/build_research_index.py`. Do not edit by hand.",
        "",
        "## Overlays",
        "",
        "| Directory | Title | Status | Verified | Candidate | Blocked | Package | Modified |",
        "|---|---|---|---:|---:|---:|---|---|",
    ]
    for row in sorted(rows, key=lambda r: (-r["blocked"], r["dir"])):
        title = row["title"].replace("|", "\\|")
        lines.append(
            f"| `{row['dir']}` | {title} | {row['status']} | {row['verified']} | "
            f"{row['candidate']} | {row['blocked']} | {row['package']} | {row['modified']} |"
        )

    lines.extend([
        "",
        "## Reading order",
        "",
        "1. `FACTORY_STATUS.md` — current factory snapshot and blockers.",
        "2. `README.md` — layer overview and commands.",
        "3. Each overlay's `CLAIM_LEDGER.md` — claim-by-claim evidence state.",
        "",
    ])
    output = Path(args.output)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {output} ({len(rows)} overlays, {doc_count} documents)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
